import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { spending_summary, monthly_trends, top_merchants, savings_rate, total_income, total_expenses } = await req.json();

    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const systemPrompt = `You are a personal CFO writing a concise monthly financial report. Write a 3-4 paragraph narrative summary of the user's finances. Be specific — reference actual categories, merchants, and amounts. Highlight wins, concerns, and actionable next steps. Tone: professional but warm, like a trusted advisor. Do not use markdown headers or bullet points — write flowing paragraphs. Return only the summary text, nothing else.`;

    const userPrompt = `Monthly Financial Data:

INCOME: $${total_income}
EXPENSES: $${total_expenses}
NET: $${total_income - total_expenses}
SAVINGS RATE: ${savings_rate.toFixed(1)}%

SPENDING BY CATEGORY:
${spending_summary}

MONTHLY TRENDS:
${monthly_trends}

TOP MERCHANTS:
${top_merchants}

Write a narrative monthly financial summary.`;

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: userPrompt },
        ],
      }),
    });

    if (!response.ok) {
      const errText = await response.text();
      console.error("AI gateway error:", response.status, errText);
      throw new Error("AI gateway error");
    }

    const data = await response.json();
    const summary = data.choices?.[0]?.message?.content || "Unable to generate summary.";

    return new Response(JSON.stringify({ summary }), {
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  } catch (e) {
    console.error("monthly-summary error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
